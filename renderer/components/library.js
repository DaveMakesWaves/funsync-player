  async _loadSpeedStatsForVideo(video, cardEl) {
    if (!video.hasFunscript || !video.funscriptPath) return;
    try {
      const content = await this._readFunscriptResilient(video);
      if (!content) return;
      const parsed = JSON.parse(content);
      const actions = parsed?.actions;
      if (actions && actions.length >= 2) {
        const stats = computeSpeedStats(actions);
        video.avgSpeed = stats.avgSpeed;
        video.maxSpeed = stats.maxSpeed;
        if (!video._heatmapBins) video._heatmapBins = computeBins(actions);
        if (cardEl) {
          const target = cardEl.querySelector('.library__card-info')
            || cardEl.querySelector('.library__list-badges');
          if (target) this._addSpeedBadge(target, stats);
          // List view's row strip and the grid card's opt-in strip both
          // draw from the same freshly-computed bins.
          const heatmap = cardEl.querySelector('.library__list-heatmap')
            || cardEl.querySelector('.library__card-heatmap-canvas');
          if (heatmap && video._heatmapBins) renderBins(heatmap, video._heatmapBins);
        }
      }
    } catch { /* ignore */ }
  }

