  /**
   * Bulk "Assign script to selected" (zaikechi #209/#221 — the enabler
   * for many-videos-per-script + balance-shuffle-by-script): multi-select
   * N videos → native funscript picker ONCE. NON-DESTRUCTIVE (Dave,
   * 2026-08-04): a video that already has a main script keeps it — the
   * picked script is added as a VARIATION instead (manualVariants, same
   * shape as the player's "+ Add variation" flow). Only videos with no
   * script at all get it as their single-axis association (existing
   * multi/custom slots preserved). Registers with the backend so the
   * phone/VR see new pairings.
   */
  async _bulkAssignScript() {
    if (this._selectedPaths.size === 0) return;
    const picked = await window.funsync.selectFunscript();
    if (!picked?.path) return; // dialog cancelled
    const associations = { ...(this._settings.get('library.associations') || {}) };
    const manualVariants = { ...(this._settings.get('library.manualVariants') || {}) };
    // Variation label = script filename without extension (same default the
    // single-video add-variation naming modal suggests).
    const variantLabel = (picked.name || picked.path.split(/[\\/]/).pop() || '')
      .replace(/\.funscript$/i, '');
    let assignedMain = 0;
    let addedVariation = 0;
    for (const path of this._selectedPaths) {
      const video = this._videosByPath?.get(path) || (this._videos || []).find((v) => v.path === path);
      const entry = normalizeAssociation(associations[path]);
      const mainPath = video?.funscriptPath || entry.single || null;
      if (!mainPath) {
        // No script yet → the picked script becomes the main association.
        associations[path] = buildAssociationEntry('single', picked.path, entry.multi, entry.custom);
        if (video) {
          video.hasFunscript = true;
          video.funscriptPath = picked.path;
          video._manualAssociation = true;
        }
        assignedMain++;
      } else {
        // Has a main script → NEVER overwrite; add as a variation instead.
        if (mainPath === picked.path) continue; // it already IS the main
        const list = manualVariants[path] ? [...manualVariants[path]] : [];
        if (!list.some((v) => v.path === picked.path)) {
          list.push({ label: variantLabel, path: picked.path, name: picked.name || variantLabel });
          manualVariants[path] = list;
          addedVariation++;
        }
      }
    }
    if (assignedMain > 0) this._settings.set('library.associations', associations);
    if (addedVariation > 0) this._settings.set('library.manualVariants', manualVariants);
    // Phone / VR content server must see the new pairings too.
    this._registerWithBackend();
    const { showToast } = await import('../js/toast.js');
    showToast(t('library.bulkScriptAssigned', {
      count: assignedMain + addedVariation,
      name: picked.name || '',
    }), 'success');
    this._exitSelectMode();
    // Re-render so cards pick up funscript badges / move to the Matched tab.
    this._applyFilters();
  }

