// Now that thumbnails are generated by the backend's ffmpeg (off-process)
// instead of hidden <video> elements in the renderer, the renderer no
// longer competes with the main player for GPU decode slots. The bottleneck
// is backend ffmpeg subprocess throughput, not GPU contention.
//
// Concurrency was 8 originally, lowered to 4 after a VR user reported
// startup timeouts on 6K/8K HEVC content: software HEVC decode at 8K
// runs ~5-10 fps, and 8 simultaneous decodes saturate a typical desktop
// CPU so badly that each subprocess exceeds its 60s timeout. Halving to
// 4 keeps per-decode CPU headroom while still parallelising the common
// H.264 case. If you raise this again, benchmark against an 8K HEVC
// sample (`Test.mp4` is H.264 1080p — won't catch the regression).
const MAX_CONCURRENT_THUMBNAILS = 4;

/**
 * Resolve the seek percentage for a video's thumbnail from its optional
 * custom-thumbnail override. Returns the clamped 0..1 `seekPct` when the
 * user pinned a specific frame, else the default 10% mark. Kept pure +
 * exported so the override/clamp rules are unit-testable.
 *
 * @param {{seekPct?: number}|undefined|null} custom
 * @returns {number}
 */
export function resolveThumbSeekPct(custom) {
  const pct = custom?.seekPct;
  if (typeof pct === 'number' && isFinite(pct)) {
    return Math.min(0.999, Math.max(0, pct));
  }
  return 0.1;
}

/**
 * Build the backend thumbnail-request options for a video's optional
 * custom-thumbnail override. A user-picked frame requests `exact: true`
 * so the backend grabs the frame AT the picked timestamp (frame-accurate,
 * matching the picker's WYSIWYG preview) instead of the default fast path
 * (nearest keyframe + a 10s minimum seek), which silently produced a
 * different frame than the one chosen. Auto thumbs (no override) keep the
 * cheap default — the bulk library queue never pays the exact-decode cost.
 *
 * @param {{seekPct?: number}|undefined|null} custom
 * @returns {{seekPct: number, exact: boolean}}
 */
export function thumbRequestOpts(custom) {
  const hasPin = typeof custom?.seekPct === 'number' && isFinite(custom.seekPct);
  return { seekPct: resolveThumbSeekPct(custom), exact: hasPin };
}

/**
 * Resolve a user-uploaded custom thumbnail IMAGE from a video's override
 * entry. Returns the cached image path for `{ type: 'image', imagePath }`
 * entries, else null (frame pins and legacy `{ seekPct }` entries are
 * handled by `thumbRequestOpts`). Pure + exported so all thumb surfaces
 * (library, playlists, categories, Up Next) share one rule.
 *
 * @param {{type?: string, imagePath?: string}|undefined|null} custom
 * @returns {string|null}
 */
export function customThumbImagePath(custom) {
  return (custom?.type === 'image'
    && typeof custom.imagePath === 'string'
    && custom.imagePath.length > 0) ? custom.imagePath : null;
}

