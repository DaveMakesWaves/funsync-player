// electron-conf is ESM-only → dynamic import. The import itself is the
// expensive half of initStore (~1s cold on the startup trace), and it
// touches nothing app-specific (no userData read — only `new Conf` does
// that), so main.js kicks it off at module load via preloadModule() and
// it resolves in parallel with Chromium init + the recovery sweep.
let _confModulePromise = null;

function preloadModule() {
  if (!_confModulePromise) _confModulePromise = import('electron-conf');
  return _confModulePromise;
}

async function initStore() {
  const mod = await preloadModule();
  Conf = mod.default || mod.Conf;
  conf = new Conf({ defaults: DEFAULTS });
  _appliedMigrations = runMigrations();
  return conf;
}

// --- One-time migrations of stored values ---
//
// The read-time default merge (applyDefaults) only fills keys that are
// absent, and electron-conf wrote the WHOLE DEFAULTS block into every config
// file it created. So a default that shipped wrong stays on every install
// first run while it shipped, exactly as if the user had picked it, and
// changing DEFAULTS never reaches them (the V54 lesson). A migration here
// rewrites such a value ONCE: its id is recorded in `_migrations` the first
// time it runs, whatever it found, so a value the user sets afterwards (the
// same one included) is never touched again. getAll() carries the record, so
// a snapshot, and a restore or recovery from one, keeps it too.
const MIGRATIONS = [
  {
    // T-Code update rate 25 Hz → 60 Hz (V77, found verifying EroScripts
    // #204). 25 was the default only in v0.8.0, so it sits in every config
    // created by a fresh 0.8.0 install (Jul 31 - Aug 6 2026). It is the rate
    // that aliased fast vibration; 0.9.0 fixed that with keyframe output and
    // made 60 the default, but those installs kept running at 25. A 25 on
    // disk cannot be told from a deliberate pick, so this moves it once; any
    // other value is the user's and is left alone.
    id: 'tcodeUpdateRate25to60',
    run() {
      if (conf.get('settings.tcode.updateRateHz') !== 25) return false;
      _write('settings.tcode.updateRateHz', 60);
      return true;
    },
  },
];

let _appliedMigrations = [];

/**
 * Run every migration not yet recorded in `_migrations`, record each one,
 * and return the ids that changed something (main.js logs them). A
 * migration that throws is not recorded, so it is tried again next launch.
 */
function runMigrations() {
  const stored = conf.get('_migrations');
  const done = stored && typeof stored === 'object' && !Array.isArray(stored) ? { ...stored } : {};
  const applied = [];
  for (const migration of MIGRATIONS) {
    if (done[migration.id]) continue;
    try {
      if (migration.run()) applied.push(migration.id);
    } catch (err) {
      console.warn(`[Store] migration ${migration.id} failed:`, err?.message || err);
      continue;
    }
    done[migration.id] = true;
    _write('_migrations', done);
  }
  return applied;
}

/** Ids of the migrations the last initStore() applied (changed something). */
function appliedMigrations() {
  return [..._appliedMigrations];
}

// Listeners told about every write this module makes. See subscribe().
const _writeListeners = new Set();

/**
 * The ONLY way this module writes to electron-conf. Every helper below goes
 * through it, so subscribe() hears every write.
 */
function _write(...args) {
  conf.set(...args);
  for (const listener of [..._writeListeners]) {
    try { listener(); } catch (err) { console.warn('[Store] write listener threw:', err?.message || err); }
  }
}

/**
 * Subscribe to every config write. Used by data-backup to schedule a
 * debounced snapshot after significant mutations. Returns an unsubscribe
 * function.
 *
 * Called by main.js right after initStore() so the very first write
 * (which is often the migration) is observed too.
 *
 * This used to be electron-conf's `onDidAnyChange`, which misses almost
 * every write (V05, in v0.9.2 and earlier). In electron-conf 1.3.0 the
 * `store` getter returns a SHALLOW clone, and `set('settings.player.volume',
 * 80)` mutates the nested `settings` object in place, the same object the
 * listener cached as its "old value". The deep-equal check then compares
 * an object with itself, finds no change, and never calls back. Helpers
 * that edit an array from `conf.get()` and write it back (addPlaylist,
 * assignCategory...) hit the same wall. Only writes that swap a top-level
 * key for a new value were seen, so the 60 s auto-save snapshot never fired
 * for ordinary edits. Listening to our own writes cannot miss one.
 */
function subscribe(callback) {
  if (typeof callback !== 'function') return () => {};
  _writeListeners.add(callback);
  return () => { _writeListeners.delete(callback); };
}

/**
 * Fill in anything missing from `stored` using `defaults`, recursively.
 *
 * electron-conf's `defaults` only seed a config file that does not exist yet.
 * Once `config.json` has a `settings.player` object, a NEW key added to
 * DEFAULTS under it is never merged in — `conf.get()` returns `undefined`
 * for it forever, on every existing install.
 *
 * That is not a theoretical gap. Verified against a live app on 2026-08-25:
 * `handy.syncRounds` and `player.orgasmSwitchMode` (both present in the file)
 * read back fine, while `player.rangeLivePreview`, `player.hwVideoDecode`,
 * `player.randomVariantOnPlay` and `library.showResumeProgress` — all declared
 * in DEFAULTS, none written to the file — every one returned `undefined`.
 *
 * It bites unevenly, which is why it went unnoticed. A setting read as
 * `get(x) === true` or `=== false` gets the intended default from `undefined`
 * by luck. `player.preferMultiAxis` is read as `!== 'multi'`, so `undefined`
 * fails it and multi-axis auto-promotion stayed off for every existing user
 * even after the default was corrected — the exact bug we thought we had
 * fixed twice (stingray).
 *
 * Merging at READ time rather than writing defaults into the file on upgrade:
 * a read-time merge is idempotent, cannot corrupt a config, and never
 * resurrects a key the user cleared on purpose.
 *
 * Rules: only `undefined` is filled — `null`, `0`, `''` and `false` are real
 * stored values and survive. Arrays are taken whole, never merged
 * element-wise, so a user's emptied list stays empty.
 */
function applyDefaults(stored, defaults) {
  if (stored === undefined) {
    return defaults === undefined ? undefined : JSON.parse(JSON.stringify(defaults));
  }
  const bothPlainObjects = stored !== null
    && typeof stored === 'object' && !Array.isArray(stored)
    && defaults !== null && defaults !== undefined
    && typeof defaults === 'object' && !Array.isArray(defaults);
  if (!bothPlainObjects) return stored;

  const out = { ...stored };
  for (const key of Object.keys(defaults)) {
    out[key] = applyDefaults(stored[key], defaults[key]);
  }
  return out;
}

function getAll() {
  const raw = JSON.parse(JSON.stringify({
    settings: conf.get('settings'),
    playlists: conf.get('playlists'),
    categories: conf.get('categories'),
    videoCategories: conf.get('videoCategories'),
    _migrated: conf.get('_migrated'),
    // The one-time migration record (runMigrations). Snapshots are built
    // from getAll() and a restore writes one back as the whole config.json,
    // so without it a restore would re-run a migration over a value the
    // user had picked since.
    _migrations: conf.get('_migrations'),
  }));
  // The renderer's DataService caches this wholesale and answers every
  // `get()` from it, so anything missing here is missing app-wide.
  raw.settings = applyDefaults(raw.settings, DEFAULTS.settings);
  return raw;
}

function getSetting(path) {
  const stored = conf.get(`settings.${path}`);
  if (stored !== undefined) return stored;
  // Same fallback for main-process reads, which never touch getAll().
  let fallback = DEFAULTS.settings;
  for (const key of String(path).split('.')) {
    if (fallback == null || typeof fallback !== 'object') return undefined;
    fallback = fallback[key];
  }
  return fallback === undefined
    ? undefined
    : JSON.parse(JSON.stringify(fallback));
}

